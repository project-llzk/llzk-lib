#!/usr/bin/env python3
"""Generate FileCheck directives for LLZK lit tests.

This script is a utility to add FileCheck patterns to an MLIR or LLZK file. It was
adapted from the LLVM project's mlir/utils/generate-test-checks.py script.

NOTE: The input .mlir/.llzk is expected to be printed IR, not a stripped-down
variant.

Example usage:
$ scripts/generate-test-checks.py foo.llzk
$ llzk-opt foo.llzk --canonicalize | scripts/generate-test-checks.py
$ llzk-opt foo.llzk --canonicalize | scripts/generate-test-checks.py --source foo.llzk
$ llzk-opt foo.llzk --canonicalize | scripts/generate-test-checks.py --source foo.llzk -i
$ llzk-opt foo.llzk --canonicalize | scripts/generate-test-checks.py --source foo.llzk -i --source_delim_regex='gpu.func @'

In-place updates refuse to modify a dirty Git worktree, including untracked
files, unless --allow-dirty is specified.

In-place updates require --source, cannot be combined with --output, and
replace the source only after generation succeeds. Review generated checks
before using --inplace; they are heuristic and are not authoritative test
specifications.

The script heuristically generates FileCheck directives for the input. By
default it also inserts FileCheck variable substitutions for SSA value names.
If --source is specified, the script inserts generated CHECKs before source
lines matched by --source_delim_regex.
Generated attribute-definition checks stay in the source segment that contains
their definitions, preserving their order when the source is split into
multiple segments.

The script is designed to make adding checks to a test case fast, it is *not*
designed to be authoritative about what constitutes a good test!
"""

