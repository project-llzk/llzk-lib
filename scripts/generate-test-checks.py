    def test_workspace_is_dirty_handles_localized_non_repository_and_status_failure(self):
        """Non-repository paths are clean while other Git failures are reported."""
        non_repository_source = self.write_file(
            "non-repository/source.llzk", "module {}\n"
        )
        repository_source = self.write_file(
            "repository/source.llzk", "module {}\n"
        )
        (repository_source.parent / ".git").mkdir()
        non_repository = subprocess.CompletedProcess(
            args=[],
            returncode=128,
            stdout="",
            stderr="fatal: dépôt Git introuvable",
        )
        status_failure = subprocess.CompletedProcess(
            args=[], returncode=2, stdout="", stderr="fatal: injected status failure"
        )

        with mock.patch.dict(
            globals(),
            {"_git_environment_without_local_vars": mock.Mock(return_value={})},
        ), mock.patch.object(
            subprocess, "run", side_effect=[non_repository, status_failure]
        ):
            self.assertFalse(workspace_is_dirty(non_repository_source))
            with self.assertRaisesRegex(RuntimeError, "injected status failure"):
                workspace_is_dirty(repository_source)

    def test_workspace_is_dirty_rejects_malformed_repository_metadata(self):
        """A broken .git entry is a status failure rather than a clean worktree."""
        source = self.write_file("broken/source.llzk", "module {}\n")
        self.write_file("broken/.git", "gitdir: missing\n")

        with self.assertRaises(RuntimeError):
            workspace_is_dirty(source)
